#!/usr/bin/env node
// Generate templates/index.js — the manifest the generator HTML loads to offer
// Template mode (classic <script>, works from file://; only metadata, the base
// art itself is fetched per template when served over http).
//
//   node scripts/build-manifest.mjs

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

import { loadRegistry } from '../src/templates/registry.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, '..', 'templates');

const { templates, errors } = loadRegistry(dir, { withL3: false }); // L3 = the 3 product types already
const list = templates.map(({ id, name, kind, base, params, bindings, sample }) => ({ id, name, kind, base, params, bindings, sample }));

const out = `// Generated by scripts/build-manifest.mjs — do not edit by hand.
// Metadata for Template mode in the HTML generator. Rebuild: npm run build.
(typeof window !== 'undefined' ? window : globalThis).LADDER_TEMPLATES = ${JSON.stringify(list, null, 1)};
`;
const dest = join(dir, 'index.js');
writeFileSync(dest, out);
console.log(`wrote ${dest} (${list.length} templates${errors.length ? `, ${errors.length} FAILED: ${errors.map((e) => e.dir).join(', ')}` : ''})`);
if (errors.length) process.exit(1);
